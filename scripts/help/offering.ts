/** 캡처 위 빨간 번호와 맞춘 설명 목록 (1부터)
 *  ※ globals.css 의 `.prose ul { list-style-type: disc !important }` 때문에 ul 대신 div 로 만든다. */
function legend(items: string[], start = 1): string {
  return (
    `<div style="margin:8px 0 16px">` +
    items
      .map(
        (t, i) =>
          `<div style="display:flex;align-items:flex-start;gap:4px;margin:7px 0;line-height:1.65">` +
          `<span style="flex:none;margin-top:0.12em">${num(start + i)}</span><span>${t}</span></div>`,
      )
      .join("") +
    `</div>`
  );
}

/**
 * 본문 꾸밈 — 사이트에 typography 플러그인이 없어 .prose 의 h2/h3/p 가 본문과 같은 모양이 되므로
 * inline style 을 입힌다. <kbd> 는 sanitize 허용 태그가 아니라 span 으로 바꾼다.
 */
function styled(html: string): string {
  return html
    .replace(/<h2>/g, `<h2 style="font-size:1.45em;font-weight:700;color:#1e3a8a;margin:4px 0 12px;padding-bottom:6px;border-bottom:2px solid #dbeafe">`)
    .replace(/<h3>/g, `<h3 style="font-size:1.15em;font-weight:700;color:#111827;margin:28px 0 10px;padding-left:10px;border-left:4px solid #e11d48">`)
    .replace(/<p>/g, `<p style="margin:8px 0;line-height:1.7">`)
    .replace(/<hr>/g, `<hr style="margin:28px 0;border:0;border-top:1px solid #e5e7eb">`)
    .replace(/<kbd>/g, `<span style="display:inline-block;padding:0 6px;border:1px solid #cbd5e1;border-bottom-width:2px;border-radius:4px;background:#f8fafc;font-size:0.85em;font-family:monospace;line-height:1.5">`)
    .replace(/<\/kbd>/g, `</span>`);
}

